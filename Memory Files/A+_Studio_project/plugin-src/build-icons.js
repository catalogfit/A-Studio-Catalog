// Generates plugin-src/icon-fallback.js: the plugin's own copy of every catalogued icon whose
// backup SVG is a clean vector glyph (backend/icons/index.json + backend/icons/*.svg).
//
// The renderer looks for icons on the canvas first (production, then ICON BANK, on every page).
// This copy is the LAST resort, for a name the catalogue knows but the canvas search cannot reach:
// the icon was moved, regrouped or restyled, or the run is in a different Figma file. It is the
// same artwork, so it is the right icon, never a substitute.
//
// Only clean glyphs are bundled. An SVG is skipped when it embeds a raster (<image>) or carries
// a full-canvas background rect (most backups were exported with the frame's grey fill), because
// either would draw a grey square or a blurry bitmap inside the ring.
//
//   node plugin-src/build-icons.js        (build.js runs it)
var fs = require('fs');
var path = require('path');

var SRC = __dirname;
var ICONS = path.join(SRC, '..', 'backend', 'icons');
var OUT = path.join(SRC, 'icon-fallback.js');

function key(s) { return String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim(); }
function cleanGlyph(svg) {
  if (/<image\b/i.test(svg)) return 'embeds a raster image';
  var vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  if (!vb) return 'has no viewBox';
  var bg = new RegExp('<rect[^>]*\\bwidth="' + vb[1].replace('.', '\\.') + '"[^>]*\\bheight="' + vb[2].replace('.', '\\.') + '"[^>]*\\bfill="#', 'i');
  if (bg.test(svg)) return 'has a background rect';
  return null;
}

var cat = JSON.parse(fs.readFileSync(path.join(ICONS, 'index.json'), 'utf8'));
var out = {}, skipped = [];
(cat.icons || []).forEach(function (ic) {
  var file = ic.files && ic.files.svg;
  if (!file || !fs.existsSync(path.join(ICONS, file))) return;
  var svg = fs.readFileSync(path.join(ICONS, file), 'utf8').trim();
  var why = cleanGlyph(svg);
  if (why) { skipped.push(ic.name + ' (' + why + ')'); return; }
  // How big the glyph sits in its ring, so the production rebuild keeps the designer's proportion.
  var b = ic.bank || {};
  var ratio = (b.glyphSize && b.ringDiameter) ? Math.max(b.glyphSize[0], b.glyphSize[1]) / b.ringDiameter : 0.51;
  out[key(ic.name)] = { name: ic.name, file: file, svg: svg, glyphRatio: Math.round(ratio * 10000) / 10000 };
});

var body = '// GENERATED by plugin-src/build-icons.js from backend/icons — do not edit by hand.\n' +
  '// Clean-vector icon glyphs the renderer may draw when the canvas has no icon of that name.\n' +
  'var ICON_FALLBACK = ' + JSON.stringify(out, null, 1) + ';\n';
fs.writeFileSync(OUT, body);
console.log('built plugin-src/icon-fallback.js (' + Object.keys(out).length + ' icon(s): ' +
  Object.keys(out).map(function (k) { return out[k].name; }).join(', ') + '; skipped ' + skipped.length + ')');
